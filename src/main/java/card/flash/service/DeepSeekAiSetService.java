package card.flash.service;

import card.flash.dto.AiSetCardDto;
import card.flash.dto.AiSetGenerationRequest;
import card.flash.dto.AiSetGenerationResponse;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

@Service
public class DeepSeekAiSetService {

    private final HttpClient httpClient = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(10))
            .build();
    private final ObjectMapper objectMapper;
    private final String apiKey;
    private final String chatUrl;
    private final String model;

    public DeepSeekAiSetService(
            ObjectMapper objectMapper,
            @Value("${deepseek.api-key:}") String apiKey,
            @Value("${deepseek.chat-url:https://api.deepseek.com/chat/completions}") String chatUrl,
            @Value("${deepseek.model:deepseek-chat}") String model
    ) {
        this.objectMapper = objectMapper;
        this.apiKey = apiKey;
        this.chatUrl = chatUrl;
        this.model = model;
    }

    public AiSetGenerationResponse generateSet(AiSetGenerationRequest request) {
        if (apiKey == null || apiKey.isBlank()) {
            throw new IllegalStateException("DEEPSEEK_API_KEY is not configured");
        }

        String title = request.title() == null || request.title().isBlank()
                ? "AI vocabulary set"
                : request.title().trim();
        String text = request.text() == null ? "" : request.text().trim();
        if (text.isBlank()) {
            return new AiSetGenerationResponse(title, "Generated by AI: 0 cards", List.of());
        }

        try {
            String content = requestDeepSeekCards(title, text);
            List<AiSetCardDto> cards = parseCards(content);
            return new AiSetGenerationResponse(title, "Generated by DeepSeek AI: " + cards.size() + " cards", cards);
        } catch (IOException | InterruptedException exception) {
            if (exception instanceof InterruptedException) {
                Thread.currentThread().interrupt();
            }
            throw new IllegalStateException("DeepSeek request failed", exception);
        }
    }

    private String requestDeepSeekCards(String title, String text) throws IOException, InterruptedException {
        Map<String, Object> payload = Map.of(
                "model", model,
                "temperature", 0.2,
                "max_tokens", 2200,
                "messages", List.of(
                        Map.of(
                                "role", "system",
                                "content", """
                                        You create English-Russian flashcards from user text.
                                        Extract important English vocabulary from the text.
                                        Return only valid JSON with this shape:
                                        {"cards":[{"term":"english word or phrase","definition":"russian translation"}]}
                                        No markdown, no explanation.
                                        Keep 12 to 30 useful cards.
                                        """
                        ),
                        Map.of(
                                "role", "user",
                                "content", "Title: " + title + "\n\nText:\n" + text
                        )
                )
        );

        HttpRequest httpRequest = HttpRequest.newBuilder()
                .uri(URI.create(chatUrl))
                .timeout(Duration.ofSeconds(60))
                .header("Authorization", "Bearer " + apiKey)
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(objectMapper.writeValueAsString(payload)))
                .build();

        HttpResponse<String> response = httpClient.send(httpRequest, HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() >= 400) {
            throw new IOException("DeepSeek API returned HTTP " + response.statusCode());
        }

        JsonNode root = objectMapper.readTree(response.body());
        return root.path("choices").path(0).path("message").path("content").asText("");
    }

    private List<AiSetCardDto> parseCards(String content) throws IOException {
        String json = stripMarkdownFence(content);
        JsonNode root = objectMapper.readTree(json);
        JsonNode cardNodes = root.path("cards");
        List<AiSetCardDto> cards = new ArrayList<>();

        if (!cardNodes.isArray()) {
            return cards;
        }

        for (JsonNode cardNode : cardNodes) {
            String term = cardNode.path("term").asText("").trim();
            String definition = cardNode.path("definition").asText("").trim();
            if (!term.isBlank() && !definition.isBlank()) {
                cards.add(new AiSetCardDto(term, definition));
            }
        }
        return cards;
    }

    private String stripMarkdownFence(String content) {
        String trimmed = content == null ? "" : content.trim();
        if (trimmed.startsWith("```")) {
            trimmed = trimmed.replaceFirst("^```(?:json)?", "").trim();
            trimmed = trimmed.replaceFirst("```$", "").trim();
        }
        return trimmed;
    }
}
